const sheets = [
  "composition",
  "head",
  "mane",
  "torso",
  "arms",
  "legs",
  "weapon",
  "finish",
].map((name) => `/assets/boss-original-${name}-steps-v5.png`);
const chapters = [];
function addChapter(title, focusTitle, layer, tools, items) {
  const number = chapters.length;
  chapters.push({
    id: `boss-original-v5-chapter-${number + 1}`,
    title,
    steps: items.map(([title, action, checkpoint, commonMistake], panel) => ({
      id: `boss-original-v5-${number * 12 + panel + 1}`,
      title,
      goal: title,
      actions: [action],
      checkpoint,
      commonMistake,
      technique:
        number === 7
          ? panel === 0
            ? "ink"
            : panel < 8
              ? "fill"
              : "shade"
          : number === 6 && panel >= 4
            ? "ink"
            : panel > 8
              ? "ink"
              : "sketch",
      focusTitle,
      layer,
      tools,
      sheet: sheets[number],
      panel,
      columns: 4,
      rows: 3,
    })),
  });
}

