const sheetNames = [
  "composition",
  "head",
  "torso",
  "arms",
  "legs",
  "ink",
  "finish",
];
const sheets = sheetNames.map(
  (name) => `/assets/duck-original-${name}-steps-v5.png`,
);
const step = (title, action, checkpoint, commonMistake) => ({
  title,
  goal: title,
  actions: [action],
  checkpoint,
  commonMistake,
});
const chapter = (index, title, focusTitle, layer, tools, steps) => ({
  id: `duck-original-v5-${sheetNames[index]}`,
  title,
  steps: steps.map((item, panel) => ({
    ...item,
    id: `duck-original-v5-${index * 12 + panel + 1}`,
    technique:
      index === 5
        ? "ink"
        : index === 6
          ? panel === 0
            ? "ink"
            : panel < 8
              ? "fill"
              : "shade"
          : panel > 8
            ? "ink"
            : "sketch",
    focusTitle,
    sheet: sheets[index],
    panel,
    columns: 4,
    rows: 3,
    layer,
    tools,
  })),
});

