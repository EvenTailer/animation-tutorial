function add(id, kind, variant, meta, rows) {
  const steps = rows.map(
    (
      [operation, title, text, checkpoint, mistake, technique = "sketch", why],
      phase,
    ) => ({
      title,
      text,
      checkpoint,
      mistake,
      technique,
      interaction:
        kind === "files" ||
        Object.hasOwn(interfaceTools, operation) ||
        [
          "frames",
          "first-half",
          "play",
          "loop-check",
          "play-check",
          "model-check",
          "trace-chains",
          "rotation-test",
          "value-check",
          "study-review",
        ].includes(operation) ||
        (id === "w5-l3" && operation === "compare")
          ? "menu"
          : "draw",
      layer: activeLayer(id, kind, operation, technique),
      why: why || purposes[operation] || skillPurposes[kind],
      tool: interfaceTools[operation] || tools[technique],
      visual: {
        kind,
        variant,
        phase,
        total: rows.length,
        operation,
        focus: title,
        alt: `${title}. ${checkpoint}`,
      },
    }),
  );
  foundationLessons[id] = {
    id,
    foundation: true,
    setup: {
      canvas: "1200 × 1200 px, квадратный пробный лист",
      layers: [
        "01 Бумага — светлый фон",
        "02 Эскиз — отдельный прозрачный слой",
      ],
    },
    prerequisites: [],
    duration: 25,
    ...meta,
    steps,
    checklist: meta.checklist || [
      steps.at(-1).checkpoint,
      "Могу повторить показанное действие на новом месте листа",
      "Сохранён редактируемый исходник",
    ],
    mistake: meta.mistake || steps.at(-1).mistake,
  };
  // Names below the setup are the same names used by the active step. Extra
  // working layers are introduced when their action is reached, not at once.
  const setup = foundationLessons[id].setup;
  if (kind === "files") {
    setup.canvas =
      "Используй размер уже нарисованного проекта. Новый холст для этого занятия не нужен.";
    setup.layers = [
      "Сохрани существующие слои исходника; экспортируй только рабочую копию.",
    ];
  } else {
    if (!meta.setup) setup.layers = ["Фон — светлая бумага"];
    if (kind === "tablet")
      setup.layers = [
        "01 Бумага — светлый фон",
        "02 Проба — прозрачный слой для линий",
      ];
    for (const step of steps)
      if (
        !step.layer.startsWith("Все рабочие") &&
        !setup.layers.some((name) => name.startsWith(step.layer))
      )
        setup.layers.push(step.layer);
  }
}

