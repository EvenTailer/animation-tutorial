function activeLayer(id, kind, operation, technique) {
  if (kind === "files") return "Существующий проект / файлы экспорта";
  if (["foot-path", "keys-compare"].includes(operation))
    return "01 Направляющие";
  if (id === "w8-l2" && operation === "inbetween")
    return "03 Промежуточный кадр";
  if (
    [
      "compare",
      "save",
      "export",
      "study-review",
      "play",
      "loop-check",
      "play-check",
      "keys-compare",
      "model-check",
    ].includes(operation)
  )
    return "Все рабочие слои — проверка";
  if (kind === "tablet")
    return operation === "canvas" ? "01 Бумага" : "02 Проба";
  if (id === "w3-l1")
    return operation === "bounds" ? "01 Ориентиры" : "02 Манекен";
  if (id === "w6-l1")
    return operation === "levels"
      ? "01 Общие уровни"
      : operation.startsWith("front")
        ? "02 Фронт"
        : "03 Профиль";
  if (id === "w6-l3")
    return (
      {
        "upper-arm": "03 Плечо R",
        forearm: "04 Предплечье R",
        hand: "05 Кисть R",
        "rotation-test": "04 Предплечье R",
      }[operation] || "02 Исходная рука"
    );
  if (id === "w10-l1")
    return operation === "lion-bounds"
      ? "01 Размещение"
      : technique === "fill"
        ? "03 Силуэт"
        : "02 Крупные формы";
  if (id === "w10-l2")
    return (
      {
        "study-bounds": "01 Размещение и оси",
        "study-contour": "03 Контур",
        "study-base": "04 Базовый цвет",
        "study-shadow": "05 Тени",
      }[operation] || "02 Эскиз форм"
    );
  if (id === "w2-l3" && operation === "forms") return "03 Контур";
  if (["axis", "levels", "ground", "weight-axis", "light"].includes(operation))
    return "01 Направляющие";
  return layers[technique];
}
